  /// Mapeamento reverso automático: texto em espanhol -> chave del diccionario.
  static final Map<String, String> _spanishToKey = _buildSpanishToKey();

  static Map<String, String> _buildSpanishToKey() {
    final map = <String, String>{};
    final esDict = _values['es']!;
    for (final entry in esDict.entries) {
      map[entry.value.trim().toLowerCase()] = entry.key;
    }
    return map;
  }

  // ── Referencia global al controlador de idioma ─────────────────────────
  // Se inyecta una sola vez desde main.dart antes de runApp().
  static LocaleController? _controller;

  /// Llama esto en main.dart, después de `localeController.load()`, antes de `runApp()`.
  static void setController(LocaleController controller) {
    _controller = controller;
  }

  /// Código de idioma activo. Usa el controlador si está disponible.
  static String get _activeLang => _controller?.activeLanguageCode ?? 'es';

  /// Obtiene la traducción para una clave dada o texto directo en español según el idioma.
  ///
  /// [args] reemplaza los marcadores `{0}`, `{1}`… del texto traducido, lo que
  /// permite(parametrizar) textos como "Confirmar e Imprimir (2)".
  /// Claves disponibles para un idioma (vacío si el idioma no existe).
  /// Las usa el test de paridad es/en/pt.
  static Set<String> keys({String? langCode}) =>
      (_values[langCode ?? _controller?.activeLanguageCode ?? 'es'] ??
              const <String, String>{})
          .keys
          .toSet();

  static String tr(String keyOrSpanishText, {String? langCode, List<String>? args}) {
    final base = _traducir(keyOrSpanishText, langCode: langCode);
    if (args == null || args.isEmpty) return base;
    var salida = base;
    for (var i = 0; i < args.length; i++) {
      salida = salida.replaceAll('{$i}', args[i]);
    }
    return salida;
  }

  static String _traducir(String keyOrSpanishText, {String? langCode}) {
    final code = langCode ?? _activeLang;
    final dict = _values[code] ?? _values['es']!;

    // 1. Coincidencia directa por clave
    if (dict.containsKey(keyOrSpanishText)) {
      return dict[keyOrSpanishText]!;
    }

    // 2. Si el idioma solicitado es español, devolver el texto original
    if (code == 'es') {
      return keyOrSpanishText;
    }

    // 3. Búsqueda inversa: si pasaron texto en español ("Nuevo Camión", "Guardar", etc.)
    final normalized = keyOrSpanishText.trim().toLowerCase();
    final foundKey = _spanishToKey[normalized];
    if (foundKey != null && dict.containsKey(foundKey)) {
      return dict[foundKey]!;
    }

    // 4. Si no se encuentra, retornar el texto original como fallback
    return keyOrSpanishText;
  }

  /// Obtiene la traducción utilizando un `LocaleController` explícito.
  static String of(BuildContext context, String key, LocaleController controller) {
    return tr(key, langCode: controller.activeLanguageCode);
  }
}

/// Extensión para facilitar la traducción desde cualquier BuildContext:
/// `context.tr('Guardar')` o `context.tr('save')`
///
/// Lee el idioma desde `AppTranslations._controller` (singleton) en lugar de
/// `Localizations.maybeLocaleOf()` para garantizar que siempre refleje la
/// selección del usuario sin depender de la propagación del árbol de widgets.
extension AppTranslationContext on BuildContext {
  String tr(String keyOrText) {
    return AppTranslations.tr(keyOrText);
  }
}

/// Extensión para traducir directamente cualquier String:
/// `'Guardar'.tr(context)` o `'save'.tr()`
extension AppTranslationString on String {
  String tr([BuildContext? context, List<String>? args]) {
    return AppTranslations.tr(this, args: args);
  }

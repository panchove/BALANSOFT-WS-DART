import '../../domain/entities/weighing.dart';

class WeighingModel extends Weighing {
  const WeighingModel({
    required super.boleto,
    super.idVehiculo,
    super.remolque,
    super.idRemolque,
    super.idTransporte,
    super.idConductor,
    super.idProducto,
    super.idAlmacen,
    super.idBalanza,
    super.tipoTercero,
    super.idTercero,
    super.multiDespachoRecepcion,
    required super.fechaHoraEntrada,
    required super.pesoEntradaVehiculo,
    super.pesoEntradaRemolque,
    super.fechaHoraSalida,
    super.pesoSalidaVehiculo,
    super.pesoSalidaRemolque,
    super.pesoBruto,
    super.pesoTara,
    super.pesoNeto,
    super.pesoNetoDeclarado,
    super.pesoDiferencia,
    super.porcentajeDesviacion,
    super.diferenciaPeso,
    super.porcentajeDiferencia,
    super.densidad,
    super.litros,
    super.unidades,
    super.documento,
    super.flete,
    super.costoFlete,
    super.observaciones,
    super.numeroBoleto,
    super.motivoAnulacion,
    super.estadoBoleto,
    super.sincronizado,
    required super.createdAt,
    required super.updatedAt,
  });

  factory WeighingModel.fromEntity(Weighing w) => WeighingModel(
        boleto: w.boleto,
        idVehiculo: w.idVehiculo,
        remolque: w.remolque,
        idRemolque: w.idRemolque,
        idTransporte: w.idTransporte,
        idConductor: w.idConductor,
        idProducto: w.idProducto,
        idAlmacen: w.idAlmacen,
        idBalanza: w.idBalanza,
        tipoTercero: w.tipoTercero,
        idTercero: w.idTercero,
        multiDespachoRecepcion: w.multiDespachoRecepcion,
        fechaHoraEntrada: w.fechaHoraEntrada,
        pesoEntradaVehiculo: w.pesoEntradaVehiculo,
        pesoEntradaRemolque: w.pesoEntradaRemolque,
        fechaHoraSalida: w.fechaHoraSalida,
        pesoSalidaVehiculo: w.pesoSalidaVehiculo,
        pesoSalidaRemolque: w.pesoSalidaRemolque,
        pesoBruto: w.pesoBruto,
        pesoTara: w.pesoTara,
        pesoNeto: w.pesoNeto,
        pesoNetoDeclarado: w.pesoNetoDeclarado,
        pesoDiferencia: w.pesoDiferencia,
        porcentajeDesviacion: w.porcentajeDesviacion,
        diferenciaPeso: w.diferenciaPeso,
        porcentajeDiferencia: w.porcentajeDiferencia,
        densidad: w.densidad,
        litros: w.litros,
        unidades: w.unidades,
        documento: w.documento,
        flete: w.flete,
        costoFlete: w.costoFlete,
        observaciones: w.observaciones,
        numeroBoleto: w.numeroBoleto,
        motivoAnulacion: w.motivoAnulacion,
        estadoBoleto: w.estadoBoleto,
        sincronizado: w.sincronizado,
        createdAt: w.createdAt,
        updatedAt: w.updatedAt,
      );

  /// Desde SQLite local
  factory WeighingModel.fromLocalDb(Map<String, dynamic> map) => WeighingModel(
        boleto: map['boleto'],
        idVehiculo: map['id_vehiculo'],
        remolque: map['remolque'] == 1,
        idRemolque: map['id_remolque'],
        idTransporte: map['id_transporte'],
        idConductor: map['id_conductor'],
        idProducto: map['id_producto'],
        idAlmacen: map['id_almacen'],
        idBalanza: map['id_balanza'],
        tipoTercero: map['tipo_tercero'],
        idTercero: map['id_tercero'],
        multiDespachoRecepcion: map['multi_despacho_recepcion'] == 1,
        fechaHoraEntrada: DateTime.parse(map['fecha_hora_entrada']),
        pesoEntradaVehiculo: map['peso_entrada_vehiculo'] ?? 0.0,
        pesoEntradaRemolque: map['peso_entrada_remolque'],
        fechaHoraSalida: map['fecha_hora_salida'] != null
            ? DateTime.parse(map['fecha_hora_salida'])
            : null,
        pesoSalidaVehiculo: map['peso_salida_vehiculo'],
        pesoSalidaRemolque: map['peso_salida_remolque'],
        pesoBruto: map['peso_bruto'],
        pesoTara: map['peso_tara'],
        pesoNeto: map['peso_neto'],
        pesoNetoDeclarado: map['peso_neto_declarado'],
        pesoDiferencia: map['peso_diferencia'],
        porcentajeDesviacion: map['porcentaje_desviacion'],
        diferenciaPeso: map['diferencia_peso'],
        porcentajeDiferencia: map['porcentaje_diferencia'],
        densidad: map['densidad'],
        litros: map['litros'],
        unidades: map['unidades'],
        documento: map['documento'],
        flete: map['flete'],
        costoFlete: map['costo_flete'],
        observaciones: map['observaciones'],
        numeroBoleto: map['numero_boleto'],
        motivoAnulacion: map['motivo_anulacion'],
        estadoBoleto: _normalizarEstado(map['estado_boleto']),
        sincronizado: map['sincronizado'] == 1,
        createdAt: DateTime.parse(map['created_at']),
        updatedAt: DateTime.parse(map['updated_at']),
      );

  static String _normalizarEstado(dynamic valor) {
    final s = valor?.toString().toUpperCase() ?? 'PENDIENTE';
    if (s == 'ABIERTO' || s == 'AUTOMÁTICO') return 'PENDIENTE';
    if (s == 'COMPLETADO' || s == 'CERRADO') return 'CERRADO';
    return s;
  }

  /// A SQLite local
  Map<String, dynamic> toLocalDb() => {
        'boleto': boleto,
        'id_vehiculo': idVehiculo,
        'remolque': remolque ? 1 : 0,
        'id_remolque': idRemolque,
        'id_transporte': idTransporte,
        'id_conductor': idConductor,
        'id_producto': idProducto,
        'id_almacen': idAlmacen,
        'id_balanza': idBalanza,
        'tipo_tercero': tipoTercero,
        'id_tercero': idTercero,
        'multi_despacho_recepcion': multiDespachoRecepcion ? 1 : 0,
        'fecha_hora_entrada': fechaHoraEntrada.toIso8601String(),
        'peso_entrada_vehiculo': pesoEntradaVehiculo,
        'peso_entrada_remolque': pesoEntradaRemolque,
        'fecha_hora_salida': fechaHoraSalida?.toIso8601String(),
        'peso_salida_vehiculo': pesoSalidaVehiculo,
        'peso_salida_remolque': pesoSalidaRemolque,
        'peso_bruto': pesoBruto,
        'peso_tara': pesoTara,
        'peso_neto': pesoNeto,
        'peso_neto_declarado': pesoNetoDeclarado,
        'peso_diferencia': pesoDiferencia,
        'porcentaje_desviacion': porcentajeDesviacion,
        'diferencia_peso': diferenciaPeso,
        'porcentaje_diferencia': porcentajeDiferencia,
        'densidad': densidad,
        'litros': litros,
        'unidades': unidades,
        'documento': documento,
        'flete': flete,
        'costo_flete': costoFlete,
        'observaciones': observaciones,
        'numero_boleto': numeroBoleto,
        'motivo_anulacion': motivoAnulacion,
        'estado_boleto': estadoBoleto,
        'sincronizado': sincronizado ? 1 : 0,
        'created_at': createdAt.toIso8601String(),
        'updated_at': updatedAt.toIso8601String(),
      };
}
